"""Generate LucideIcons.kt (Compose ImageVectors) from lucide-static's icon-nodes.json.

Lucide (ISC, https://lucide.dev) — see third_party/lucide/LICENSE. Only the icons listed in ICONS are emitted,
so the app does not need materialIconsExtended (~tens of MB) nor a runtime icon dependency.
Usage: python3 tools/gen-lucide-icons.py path/to/icon-nodes.json VERSION > .../ui/icons/LucideIcons.kt
"""
import json, sys

# Kotlin name -> lucide name
ICONS = {
    "Plus": "plus", "Search": "search", "X": "x", "Settings": "settings", "CalendarClock": "calendar-clock", "Clock": "clock",
    "Pin": "pin", "Ellipsis": "ellipsis", "Pencil": "pencil", "Trash": "trash", "SquareTerminal": "square-terminal",
    "FileText": "file-text", "Brain": "brain", "Puzzle": "puzzle", "Users": "users", "Wrench": "wrench", "Check": "check",
    "CircleCheck": "circle-check", "CircleAlert": "circle-alert", "Ban": "ban", "RefreshCw": "refresh-cw",
    "ChevronDown": "chevron-down", "ChevronUp": "chevron-up", "ChevronRight": "chevron-right", "Copy": "copy",
    "Paperclip": "paperclip", "SendHorizontal": "send-horizontal", "Square": "square", "ArrowUp": "arrow-up",
    "ArrowDown": "arrow-down", "Shrink": "shrink", "Download": "download", "PanelLeft": "panel-left", "Sparkles": "sparkles",
    "Cpu": "cpu", "Palette": "palette", "Globe": "globe", "Info": "info", "Shield": "shield", "ShieldAlert": "shield-alert",
    "Languages": "languages", "Database": "database", "BookOpen": "book-open", "MessageSquare": "message-square",
    "Bot": "bot", "Server": "server", "TriangleAlert": "triangle-alert", "Eye": "eye", "EyeOff": "eye-off", "Play": "play",
    "File": "file", "Image": "image", "FolderOpen": "folder-open", "ListChecks": "list-checks",
    "ArrowDownToLine": "arrow-down-to-line", "MessageSquarePlus": "message-square-plus", "Layers": "layers",
    "Smartphone": "smartphone", "KeyRound": "key-round", "Minus": "minus", "Menu": "menu",
}

def f(v): return float(v)

def to_d(tag, a):
    if tag == "path": return a["d"]
    if tag == "line": return f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"
    if tag in ("polyline", "polygon"):
        pts = a["points"].replace(",", " ").split()
        pairs = [f"{pts[i]} {pts[i+1]}" for i in range(0, len(pts), 2)]
        return "M" + "L".join(pairs) + ("Z" if tag == "polygon" else "")
    if tag in ("circle", "ellipse"):
        cx, cy = f(a["cx"]), f(a["cy"])
        rx = f(a.get("r", a.get("rx"))); ry = f(a.get("r", a.get("ry")))
        return f"M{cx-rx} {cy}a{rx} {ry} 0 1 0 {2*rx} 0a{rx} {ry} 0 1 0 {-2*rx} 0"
    if tag == "rect":
        x, y, w, h = f(a.get("x", 0)), f(a.get("y", 0)), f(a["width"]), f(a["height"])
        rx = f(a.get("rx", a.get("ry", 0))); ry = f(a.get("ry", a.get("rx", 0)))
        if rx == 0: return f"M{x} {y}h{w}v{h}h{-w}Z"
        return (f"M{x+rx} {y}h{w-2*rx}a{rx} {ry} 0 0 1 {rx} {ry}v{h-2*ry}a{rx} {ry} 0 0 1 {-rx} {ry}"
                f"h{-(w-2*rx)}a{rx} {ry} 0 0 1 {-rx} {-ry}v{-(h-2*ry)}a{rx} {ry} 0 0 1 {rx} {-ry}Z")
    raise SystemExit(f"unsupported element {tag}")

def main():
    nodes = json.load(open(sys.argv[1])); ver = sys.argv[2]
    out = [f"""// GENERATED by tools/gen-lucide-icons.py from lucide-static {ver} — do not edit by hand.
// Lucide icons: ISC License, Copyright (c) Lucide Icons and Contributors (third_party/lucide/LICENSE).
package com.openminis.desktop.ui.icons

import androidx.compose.ui.graphics.vector.ImageVector

/** Stroke icons (24×24, 2 px, round caps/joins), tinted by Icon(). */
object Lucide {{"""]
    for kt, name in sorted(ICONS.items()):
        ds = [to_d(t, a) for t, a in nodes[name]]
        joined = ", ".join('"' + d.replace('"', '') + '"' for d in ds)
        out.append(f"    val {kt}: ImageVector by lazy {{ lucide(\"{name}\", {joined}) }}")
    out.append("}")
    print("\n".join(out))

main()
